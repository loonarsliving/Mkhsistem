-- ============================================================================
-- MK Connect — 0251: Markom AI gap-closers (monthly report, hashtag bank)
--
-- Two of the AI-feasible gaps identified in a review of the Markom module
-- against a "Social Media Specialist" role, both following existing
-- patterns exactly (no new architecture):
--
-- 1. social_monthly_content_reports -- a monthly rollup of the weekly
--    content audits that already exist (social_weekly_evaluations,
--    0111/0124). Growth numbers (follower growth %, avg weekly score,
--    best/worst week) are computed in application code from real data,
--    never by the model -- same "numbers in code, AI narrates" rule
--    already enforced for FRIDAY (lib/ai/friday/signals.ts). Property only
--    (leasehold_sales + occupancy share one account) for this first pass,
--    same scope weekly evaluation itself started at (0111) before Beauty
--    got its own version later (0133) -- Beauty can follow the same path
--    if/when there's a need.
--
-- 2. markom_hashtag_bank -- AI-generated hashtag sets per content_focus x
--    platform, following the 30/40/30 broad/medium/niche formula already
--    documented in the markom system prompt (lib/ai/domains/prompts.ts).
--    Regenerated by replacing the focus+platform's rows wholesale (not
--    accumulated) so the bank never grows stale/duplicated -- a fresh
--    weekly run is a clean slate, not a merge.
-- ============================================================================

create table public.social_monthly_content_reports (
  id uuid primary key default gen_random_uuid(),
  month_start date not null,
  report jsonb not null,
  narrative text not null,
  created_at timestamptz not null default now()
);
create unique index social_monthly_content_reports_month_start_key on public.social_monthly_content_reports (month_start);

alter table public.social_monthly_content_reports enable row level security;
create policy social_monthly_content_reports_select on public.social_monthly_content_reports for select to authenticated
  using (public.app_has_permission('content_planner.view'));

-- ----------------------------------------------------------------------------
-- markom_hashtag_bank: AI-generated, wholesale-replaced per (content_focus,
-- platform) on each refresh -- see replaceHashtagBank
-- (repositories/social.repository.ts). Same content_focus split/permission
-- pattern as social_competitor_accounts (0125): beauty gated by
-- loonars_beauty.*, leasehold_sales/occupancy by content_planner.*.
-- ----------------------------------------------------------------------------
create table public.markom_hashtag_bank (
  id uuid primary key default gen_random_uuid(),
  content_focus text not null check (content_focus in ('leasehold_sales', 'occupancy', 'beauty')),
  platform text not null check (platform in ('instagram', 'tiktok')),
  tier text not null check (tier in ('broad', 'medium', 'niche')),
  hashtag text not null,
  rationale text,
  generated_at timestamptz not null default now()
);
create index markom_hashtag_bank_focus_platform_idx on public.markom_hashtag_bank (content_focus, platform);

alter table public.markom_hashtag_bank enable row level security;
create policy markom_hashtag_bank_select on public.markom_hashtag_bank for select to authenticated
  using (
    (content_focus = 'beauty' and public.app_has_permission('loonars_beauty.view'))
    or (content_focus <> 'beauty' and public.app_has_permission('content_planner.view'))
  );
create policy markom_hashtag_bank_write on public.markom_hashtag_bank for all to authenticated
  using (
    (content_focus = 'beauty' and public.app_has_permission('loonars_beauty.manage'))
    or (content_focus <> 'beauty' and public.app_has_permission('content_planner.manage'))
  )
  with check (
    (content_focus = 'beauty' and public.app_has_permission('loonars_beauty.manage'))
    or (content_focus <> 'beauty' and public.app_has_permission('content_planner.manage'))
  );

