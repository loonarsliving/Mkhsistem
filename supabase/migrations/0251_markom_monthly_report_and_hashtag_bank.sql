-- ----------------------------------------------------------------------------
-- Monthly report: automatic on the 1st of each month (covers the just-
-- completed month), plus an on-demand manual trigger.
-- ----------------------------------------------------------------------------
create or replace function public.social_run_monthly_report_dispatch()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.ai_job_queue (job_type, payload) values ('social_monthly_content_report', '{}'::jsonb);
end;
$$;

select cron.schedule('social-monthly-content-report', '0 1 1 * *', $$select public.social_run_monthly_report_dispatch();$$);

create or replace function public.markom_request_monthly_report()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.app_has_permission('content_planner.manage') then
    raise exception 'permission denied';
  end if;

  insert into public.ai_job_queue (job_type, payload) values ('social_monthly_content_report', '{}'::jsonb);
end;
$$;

grant execute on function public.markom_request_monthly_report() to authenticated;

-- ----------------------------------------------------------------------------
-- Hashtag bank: automatic weekly refresh for all 3 foci x 2 platforms, plus
-- an on-demand manual trigger per focus+platform (mirrors
-- markom_request_competitor_discovery, 0125).
-- ----------------------------------------------------------------------------
create or replace function public.markom_run_hashtag_bank_dispatch()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_focus text;
  v_platform text;
begin
  foreach v_focus in array array['leasehold_sales', 'occupancy', 'beauty'] loop
    foreach v_platform in array array['instagram', 'tiktok'] loop
      insert into public.ai_job_queue (job_type, payload) values ('markom_hashtag_bank_refresh', jsonb_build_object('focus', v_focus, 'platform', v_platform));
    end loop;
  end loop;
end;
$$;

select cron.schedule('markom-hashtag-bank-dispatch-weekly', '0 2 * * 0', $$select public.markom_run_hashtag_bank_dispatch();$$);

create or replace function public.markom_request_hashtag_bank_refresh(p_focus text, p_platform text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_focus not in ('leasehold_sales', 'occupancy', 'beauty') then
    raise exception 'invalid focus: %', p_focus;
  end if;
  if p_platform not in ('instagram', 'tiktok') then
    raise exception 'invalid platform: %', p_platform;
  end if;

  if p_focus = 'beauty' then
    if not public.app_has_permission('loonars_beauty.manage') then
      raise exception 'permission denied';
    end if;
  else
    if not public.app_has_permission('content_planner.manage') then
      raise exception 'permission denied';
    end if;
  end if;

  insert into public.ai_job_queue (job_type, payload) values ('markom_hashtag_bank_refresh', jsonb_build_object('focus', p_focus, 'platform', p_platform));
end;
$$;

grant execute on function public.markom_request_hashtag_bank_refresh(text, text) to authenticated;
